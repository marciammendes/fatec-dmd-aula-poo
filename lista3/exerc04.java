package lista3;

public class exerc04 {
	public static void main (String[] args) {
		System.out.println("SOMA DE 1 ATÉ 100");
		System.out.println("=================\n");
		int soma = 0;
		for (int n = 1; n <= 100; n++) {
			soma += n;
		}
		System.out.println("A soma dos números de 1 até 100 é:" + soma);
	}
}
